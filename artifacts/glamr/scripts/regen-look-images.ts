// AUTO-GENERATOR for src/lib/lookImageMap.generated.ts
//
// Scans public/looks/ and intersects the filenames with every look id in
// ALL_LOOKS_FLAT, emitting a typed id -> filename map. Run after each image
// batch so the map only ever references files that actually exist on disk
// (a map entry pointing at a missing file would render a broken <img> with no
// gradient fallback).
//
//   pnpm --filter @workspace/glamr run regen:images
import { readdirSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { ALL_LOOKS_FLAT } from "../src/lib/looks";

const here = dirname(fileURLToPath(import.meta.url));
const looksDir = join(here, "..", "public", "looks");
const outFile = join(here, "..", "src", "lib", "lookImageMap.generated.ts");

// Preference order when a look somehow has more than one matching file.
const EXTS = [".jpg", ".jpeg", ".png", ".webp"];
const files = new Set(readdirSync(looksDir));

const byId = new Map<string, string>();
for (const look of ALL_LOOKS_FLAT) {
  for (const ext of EXTS) {
    const fname = look.id + ext;
    if (files.has(fname)) {
      byId.set(look.id, fname);
      break;
    }
  }
}

const ids = [...byId.keys()].sort();
const entries = ids
  .map((id) => `  ${JSON.stringify(id)}: ${JSON.stringify(byId.get(id)!)},`)
  .join("\n");

const banner =
  "// AUTO-GENERATED by scripts/regen-look-images.ts — do not edit by hand.\n" +
  "// Maps look id -> filename in public/looks/. Regenerate with:\n" +
  "//   pnpm --filter @workspace/glamr run regen:images\n";
writeFileSync(
  outFile,
  `${banner}export const lookImageMap: Record<string, string> = {\n${entries}\n};\n`,
);

const total = ALL_LOOKS_FLAT.length;
const missing = ALL_LOOKS_FLAT.filter((l) => !byId.has(l.id)).map((l) => l.id);
console.log(`Mapped ${ids.length}/${total} looks -> ${outFile}`);
console.log(`Missing images (${missing.length}):`);
if (missing.length) console.log(missing.join("\n"));
